-- Evermile: today's road leaderboard. One row per crash-free drive submitted; the client shows the best per name per day.
create table if not exists public.evermile_daily (
  id bigint generated by default as identity primary key,
  day date not null,
  name text not null check (char_length(name) between 1 and 24),
  km numeric(8, 2) not null check (km >= 0 and km <= 5000),
  created_at timestamptz not null default now()
);
create index if not exists evermile_daily_day_km on public.evermile_daily (day, km desc);
alter table public.evermile_daily enable row level security;
-- Anyone may read today's board and add a drive; nothing can be changed or removed from the client.
create policy "evermile daily read" on public.evermile_daily for select using (true);
create policy "evermile daily insert" on public.evermile_daily for insert with check (char_length(name) between 1 and 24 and km >= 0 and km <= 5000);
